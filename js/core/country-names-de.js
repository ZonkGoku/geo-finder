/** Deutscher Anzeigename, mit englischem Original als Fallback fuer nicht
 * erfasste Sonderfaelle (sollte nach der Tabelle oben nie eintreten). */
export function displayNameDe(englishName) {
  return COUNTRY_NAME_DE[englishName] || englishName;
}

/** Alle Such-Teilstrings fuer ein Land: englischer Name, deutscher Name,
 * plus etwaige Kurzform-Aliase - fuer core/country-store.js searchCountries(). */
export function searchTermsFor(englishName) {
  const terms = [englishName];
  const de = COUNTRY_NAME_DE[englishName];
  if (de) terms.push(de);
  const aliases = COUNTRY_SEARCH_ALIASES[englishName];
  if (aliases) terms.push(...aliases);
  return terms;
}
