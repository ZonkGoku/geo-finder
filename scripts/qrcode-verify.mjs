let allPass = true;
for (const { label, text, expectVersion, ref } of cases) {
  const matrix = generateQrMatrix(text);
  const refRows = ref.trim().split('\n');
  const version = (matrix.length - 17) / 4;
  const versionOk = version === expectVersion;
  const sizeOk = matrix.length === refRows.length;
  let contentOk = true;
  let firstMismatch = null;
  if (sizeOk) {
    for (let r = 0; r < matrix.length && contentOk; r++) {
      for (let c = 0; c < matrix.length; c++) {
        if (matrix[r][c] !== (refRows[r][c] === '1')) {
          contentOk = false;
          firstMismatch = `(${r},${c})`;
          break;
        }
      }
    }
  }
  const pass = versionOk && sizeOk && contentOk;
  allPass = allPass && pass;
  console.log(`${label}: ${pass ? 'MATCH' : `MISMATCH${firstMismatch ? ' at ' + firstMismatch : ''}`}`);
}
console.log(allPass ? '\nAll QR test vectors match the Python reference.' : '\nQR MISMATCH - do not ship.');
process.exit(allPass ? 0 : 1);
